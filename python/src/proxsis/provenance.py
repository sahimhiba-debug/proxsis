"""Provenance of every row: where it comes from, when, under which licence.

Every record ingested or generated by Proxsis carries a ``Provenance``.
Fictional records (synthetic world, fictional candidates) are marked
``fictif=True`` and their licence string contains ``FICTIF``.
"""

from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from typing import Any


def content_hash(payload: bytes) -> str:
    """SHA-256 hex digest of a raw payload (used for cache keys and audit)."""
    return hashlib.sha256(payload).hexdigest()


@dataclass(frozen=True)
class Provenance:
    source: str
    url: str
    retrieved_at: datetime
    license: str
    fictif: bool = False
    content_sha256: str | None = field(default=None)

    def __post_init__(self) -> None:
        for name in ("source", "url", "license"):
            if not getattr(self, name):
                raise ValueError(f"Provenance.{name} must not be empty")
        if self.retrieved_at.tzinfo is None:
            raise ValueError("Provenance.retrieved_at must be timezone-aware")

    @classmethod
    def fictional(cls, generator: str, seed: int) -> Provenance:
        return cls(
            source=f"FICTIF:{generator}",
            url=f"fictif://{generator}?seed={seed}",
            retrieved_at=datetime(2026, 10, 4, tzinfo=UTC),
            license="FICTIF — données inventées, jamais présentées comme réelles",
            fictif=True,
        )

    def as_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["retrieved_at"] = self.retrieved_at.isoformat()
        return d
