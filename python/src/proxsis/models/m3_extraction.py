"""M3 — information extraction from official publications (FR/DE).

Two extractors behind one function signature ``extract(text) -> dict``:
* ``RulesExtractor``: regular expressions written on the *development* set
  (synthetic texts, once generated by ``proxsis.textgen``, now in the Git history) — the simple baseline;
* ``LLMExtractor``: any ``LLMProvider`` (Apertus via Public AI) with a JSON
  schema (structured output / tool call).

Both outputs pass through the same post-processing: UID normalisation,
legal-entity check (a private person's name is NEVER returned) and trade
code validation. ``evaluate`` measures them on a frozen annotated set.
"""

from __future__ import annotations

import json
import re
import time
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from proxsis.entities import is_legal_entity_name, normalize_uid
from proxsis.llm.base import LLMProvider
from proxsis.taxonomy import TRADES

DOC_TYPES = ("permis_construire", "adjudication", "registre_commerce")
RC_SUBTYPES = (
    "nouvelle_inscription",
    "succursale",
    "augmentation_capital",
    "changement_but",
    "transfert_siege",
    "liquidation",
    "radiation",
)

EXTRACTION_SCHEMA: dict[str, Any] = {
    "type": "object",
    "additionalProperties": False,
    "required": ["doc_type", "company_name", "uid", "commune", "amount_chf", "rc_subtype", "trades", "private_person"],
    "properties": {
        "doc_type": {"type": "string", "enum": list(DOC_TYPES)},
        "company_name": {"type": ["string", "null"]},
        "uid": {"type": ["string", "null"]},
        "commune": {"type": ["string", "null"]},
        "amount_chf": {"type": ["number", "null"]},
        "rc_subtype": {"type": ["string", "null"], "enum": [*RC_SUBTYPES, None]},
        "trades": {"type": "array", "items": {"type": "string", "enum": sorted(TRADES)}},
        "private_person": {"type": "boolean"},
    },
}

SYSTEM_PROMPT = (
    "Tu extrais des informations de publications officielles suisses (permis de construire, adjudications de "
    "marchés publics, registre du commerce), en français ou en allemand. Réponds uniquement avec un objet JSON "
    "conforme au schéma. company_name = la personne MORALE concernée (requérant, adjudicataire — premier lot —, "
    "société inscrite) avec sa forme juridique ; null si c'est une personne physique : ne recopie JAMAIS le nom "
    "d'un particulier. commune = commune du projet (permis, marché) ou siège (registre). amount_chf = coût, prix "
    "adjugé ou nouveau capital, en francs. trades = codes métiers probables parmi la liste autorisée. "
    "private_person = vrai si une personne physique est mentionnée."
)

# ---------------------------------------------------------------- rules
_LEGAL = r"(?:SA|S\.A\.|Sàrl|Sarl|AG|GmbH|Genossenschaft|Coopérative)"
_NAME = rf"([A-ZÀ-ÖØ-Þ0-9][\w&.'\- ]*?\s{_LEGAL})"
_COMPANY_AFTER = re.compile(
    r"(?:Requérant(?:e|s)?|Gesuchsteller(?:in)?|Bauherrschaft|Bauherr(?:in)?|Adjudicataire|Entreprise adjudicataire|"
    r"Soumissionnaire retenu|en faveur de|Zuschlagsempfänger(?:in)?|Berücksichtigter Anbieter|Zuschlag an|Anbieter|"
    r"Nouvelle inscription|Neueintragung)\s*:?\s*([^,;(\n]+)",
    re.IGNORECASE,
)
_RC_HEAD = re.compile(rf"{_NAME}(?:\s+en liquidation)?,\s*(?:à|au|aux|in|bisher in|CHE)[\s\-]")
_BAUGESUCH_DER = re.compile(r"Baugesuch der ([^,;(\n]+?) für")
_PLACE = r"((?:St\.\s|Ste\.\s)?[A-ZÀ-ÖÄÖÜ][^.,;:\n—()]*?)"
_COMMUNE_PATTERNS = [
    re.compile(rf"(?:[Cc]ommune|[Vv]ille) de {_PLACE}\s*[.,;:—\n]"),
    re.compile(rf"(?:Einwohnergemeinde|Gemeinde|Stadt) {_PLACE}\s*[.,;:—\n]"),
    re.compile(rf"Baupublikation (?:Stadt |Gemeinde )?{_PLACE}\s*[.,;:—\n]"),
    re.compile(r"(?:tronçon|Werkhof|Kantonsschule|bâtiment logistique de) ([A-ZÀ-ÖÄÖÜ][\w\-]+)"),
    re.compile(rf"(?:Mise à l'enquête|Décision d'adjudication|Öffentliche Auflage,? Gemeinde) — {_PLACE}\s*[.,;:\n]"),
    re.compile(rf"Zuschlag im offenen Verfahren, {_PLACE}:"),
]
_SEAT = [
    re.compile(r"Sitz neu:\s*([A-ZÄÖÜ][\w\-]+)"),
    re.compile(r"Siège transféré à ([A-ZÀ-Ö][\w\-' ]+?)[.\n]"),
    re.compile(rf"{_LEGAL}(?:\s+en liquidation)?,\s*(?:à|au|in)\s+((?:St\.\s)?[A-ZÀ-ÖÄÖÜ][\w\-.'/ ]+?),"),
]
_AMOUNT = re.compile(
    r"(?:CHF|Fr\.|francs)?\s*(\d{1,3}(?:['’ ]\d{3})+(?:[.,]\d{1,2})?|\d+(?:[.,]\d+)?)\s*(millions?|Mio\.?)?\s*"
    r"(?:\.-|\.–|–|-)?\s*(CHF|francs|Fr\.)?",
)
_RC_KEYS = [
    ("radiation", r"radiée|gelöscht|Radiation"),
    ("liquidation", r"liquidation|Liquidation|aufgelöst"),
    ("succursale", r"[Ss]uccursale|Zweigniederlassung"),
    ("augmentation_capital", r"[Aa]ugmentation du capital|Kapitalerhöhung"),
    ("transfert_siege", r"Sitz neu|Siège transféré|transfert du siège"),
    ("changement_but", r"Nouveau but|Zweck neu|neuer Zweck"),
    ("nouvelle_inscription", r"Nouvelle inscription|Neueintragung"),
]
_TRADE_KEYS: list[tuple[tuple[str, ...], str]] = [
    (
        ("macon", "manoeuvre_construction"),
        r"maçonnerie|Baumeister|BKP 211|CFC 211|immeuble|villa|halle|Neubau|"
        r"Anbau|Umbau|Aufstockung|construction d|extension|Wohnhaus|Produktionsgebäude|Hochregallager|Carport|"
        r"Logistikhalle|Erweiterung|agrandissement|transformation|Abbruch",
    ),
    (
        ("machiniste", "manoeuvre_construction"),
        r"route|chaussée|terrassement|canalisation|bitumineux|Strassenbau|"
        r"Tiefbau|Werkleitung|Belag|génie civil",
    ),
    (("electricien",), r"électri|Elektro|CFC 23\b|BKP 23\b|panneaux solaires"),
    (("installateur_sanitaire",), r"sanitaire|Sanitär|CFC 25\b|BKP 25\b|\bBad\b"),
    (("peintre",), r"[Pp]einture|Maler|CFC 285|BKP 285"),
    (("charpentier",), r"[Cc]harpente|Holzbau|Zimmerei"),
    (("grutier",), r"[Kk]ran|grue"),
]
_PRIVATE_HINTS = re.compile(
    r"Personnes inscrites|Eingetragene Personen|Gesellschafter(?:in)?:|Liquidat(?:eur|or)|Inhaber|"
    r"\b(?:M\.|Mme|Herr|Frau)\s+[A-Z]|\[particulier\]|\[Privatperson\]|Propriétaire\s*:\s*[A-Z][a-z]+ [A-Z]",
)


def _norm(s: str | None) -> str:
    if not s:
        return ""
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", s).strip().lower()


def _parse_amount(text: str) -> float | None:
    best = None
    for m in _AMOUNT.finditer(text):
        num, mult, cur_after = m.group(1), m.group(2), m.group(3)
        has_cur = "CHF" in m.group(0) or "Fr." in m.group(0) or "franc" in m.group(0)
        if not (has_cur or mult or cur_after):
            continue
        raw = re.sub(r"['’ ]", "", num)
        if "," in raw and mult:
            raw = raw.replace(",", ".")
        raw = raw.replace(",", ".")
        try:
            v = float(raw)
        except ValueError:
            continue
        if mult:
            v *= 1_000_000
        if v < 1000:
            continue
        best = v if best is None else best
        if "à CHF" in text[max(0, m.start() - 6) : m.start() + 1]:
            best = v  # "de CHF x à CHF y" -> y
    return best


def _doc_type(text: str) -> str:
    if re.search(r"FOSC|SHAB|Handelsregister|[Rr]egistre du commerce", text):
        return "registre_commerce"
    if re.search(r"[Aa]djudic|Zuschlag", text):
        return "adjudication"
    return "permis_construire"


_UP_TO_LEGAL = re.compile(rf"^(.*?\s{_LEGAL})(?=$|[\s.,;:)])")
_PREFIXES = re.compile(r"^(?:FOSC|SHAB|Mutation|Radiation|Dissolution|Neueintragung|Nouvelle inscription)\s*[.:—-]\s*")


def _clean_company(raw: str | None) -> str | None:
    if not raw:
        return None
    c = re.split(r"\s+\(|,|;", raw.strip())[0].strip(" .:")
    while _PREFIXES.match(c):
        c = _PREFIXES.sub("", c, count=1)
    m = _UP_TO_LEGAL.match(c)
    if m:
        c = m.group(1)
    c = re.sub(r"\s+en liquidation$", "", c).strip(" .:")
    return c if c and is_legal_entity_name(c) else None


class RulesExtractor:
    name = "regles"

    def extract(self, text: str) -> dict[str, Any]:
        t = _doc_type(text)
        company = None
        if t == "registre_commerce":
            m = _RC_HEAD.search(text)
            company = _clean_company(m.group(1)) if m else None
        if company is None:
            m2 = _BAUGESUCH_DER.search(text)
            if m2:
                company = _clean_company(m2.group(1))
        if company is None:
            for m in _COMPANY_AFTER.finditer(text):
                company = _clean_company(m.group(1))
                if company:
                    break
        commune = None
        if t == "registre_commerce":
            for rx in _SEAT:
                m = rx.search(text)
                if m:
                    commune = m.group(1).strip()
                    break
        else:
            for rx in _COMMUNE_PATTERNS:
                m = rx.search(text)
                if m:
                    commune = m.group(1).strip()
                    break
        rc = None
        if t == "registre_commerce":
            for code, pat in _RC_KEYS:
                if re.search(pat, text):
                    rc = code
                    break
        trades: set[str] = set()
        if t != "registre_commerce":
            for codes, pat in _TRADE_KEYS:
                if re.search(pat, text):
                    trades.update(codes)
        amount = _parse_amount(text)
        if t == "registre_commerce" and rc not in ("nouvelle_inscription", "augmentation_capital"):
            amount = None
        return post_process(
            {
                "doc_type": t,
                "company_name": company,
                "uid": normalize_uid(text),
                "commune": commune,
                "amount_chf": amount,
                "rc_subtype": rc,
                "trades": sorted(trades),
                "private_person": bool(_PRIVATE_HINTS.search(text)) or (t == "permis_construire" and company is None),
            }
        )


class LLMExtractor:
    def __init__(self, provider: LLMProvider) -> None:
        self.provider = provider
        self.name = f"llm:{provider.name}:{provider.model}"

    def extract(self, text: str) -> dict[str, Any]:
        r = self.provider.extract(SYSTEM_PROMPT, text, EXTRACTION_SCHEMA, "extraction_publication")
        return post_process(r.data)


def post_process(d: dict[str, Any]) -> dict[str, Any]:
    out = {k: d.get(k) for k in EXTRACTION_SCHEMA["properties"]}
    if out["doc_type"] not in DOC_TYPES:
        out["doc_type"] = "permis_construire"
    if out["company_name"] and not is_legal_entity_name(str(out["company_name"])):
        out["company_name"] = None  # never return a private person's name
        out["private_person"] = True
    out["uid"] = normalize_uid(out["uid"]) if out.get("uid") else None
    out["trades"] = sorted({t for t in (out.get("trades") or []) if t in TRADES})
    if out["rc_subtype"] not in RC_SUBTYPES:
        out["rc_subtype"] = None
    out["private_person"] = bool(out.get("private_person"))
    return out


# ---------------------------------------------------------------- evaluation
FIELDS = ("doc_type", "company_name", "uid", "commune", "amount_chf", "rc_subtype", "private_person")


@dataclass
class EvalReport:
    extractor: str
    n: int
    field_accuracy: dict[str, float]
    trades_f1: float
    false_fill_rate: float
    pii_leaks: int
    latency_s_mean: float
    by_lang: dict[str, dict[str, float]]
    errors: list[dict[str, Any]]


def _eq(field: str, pred: Any, gold: Any) -> bool:
    if gold is None or pred is None:
        return gold is None and pred is None
    if field == "amount_chf":
        return abs(float(pred) - float(gold)) <= 0.01 * abs(float(gold))
    if field in ("company_name", "commune"):
        return _norm(str(pred)) == _norm(str(gold))
    return bool(pred == gold)


def evaluate(extractor: Any, path: Path, private_names: list[str] | None = None) -> EvalReport:
    rows = [json.loads(line) for line in path.read_text("utf-8").splitlines() if line.strip()]
    correct = {f: 0 for f in FIELDS}
    tp = fp = fn = 0
    false_fill = null_gold = 0
    leaks = 0
    lat: list[float] = []
    errors = []
    lang_hits: dict[str, list[float]] = {}
    names = private_names or ["Dupont", "Exemple", "Muster", "Modèle", "Beispiel", "Fictif", "Mustermann"]
    for r in rows:
        t0 = time.perf_counter()
        pred = extractor.extract(r["text"])
        lat.append(time.perf_counter() - t0)
        g = r["gold"]
        row_ok = []
        for f in FIELDS:
            ok = _eq(f, pred.get(f), g.get(f))
            correct[f] += ok
            row_ok.append(ok)
            if g.get(f) is None and f not in ("private_person",):
                null_gold += 1
                false_fill += pred.get(f) is not None
            if not ok:
                errors.append({"id": r["id"], "field": f, "pred": pred.get(f), "gold": g.get(f)})
        ps, gs = set(pred.get("trades") or []), set(g.get("trades") or [])
        tp += len(ps & gs)
        fp += len(ps - gs)
        fn += len(gs - ps)
        blob = json.dumps(pred, ensure_ascii=False)
        leaks += any(n in blob for n in names)
        lang_hits.setdefault(r["lang"], []).append(sum(row_ok) / len(row_ok))
    n = len(rows)
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return EvalReport(
        extractor=getattr(extractor, "name", "?"),
        n=n,
        field_accuracy={f: correct[f] / n for f in FIELDS},
        trades_f1=2 * prec * rec / (prec + rec) if prec + rec else 0.0,
        false_fill_rate=false_fill / null_gold if null_gold else 0.0,
        pii_leaks=leaks,
        latency_s_mean=sum(lat) / n,
        by_lang={k: {"field_accuracy_mean": sum(v) / len(v)} for k, v in lang_hits.items()},
        errors=errors,
    )
